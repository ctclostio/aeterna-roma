"""Builds and runs the live runner: every lifted function linked into one x64 DLL, plus the runner that drives it.

    python scripts/lift/build_live.py              lift everything, build lifted.dll and live.exe
    python scripts/lift/build_live.py --exe-only   rebuild live.exe (loader, dispatch loop, import shims)
    python scripts/lift/build_live.py --run        build, then run; code the run reaches outside the
                                                   inventory is added (live_extra.py) and the run repeated

Output in generated/lifted/live/ (git-ignored):

    core/batch*.c, batch.h   the inventory's lifted functions and thunks (scripts/lift/build_batch.py)
    core/live_extra.c        lifted functions of port/lifted_live/extra_functions.tsv
    core/live_ranges.c       address range -> owning function
    lifted.dll               the lifted functions and port/lifted_live/live_rt.c
    live.exe                 port/lifted_live/live_main.c
    image.bin                the mapped image the runner loads
    last_run.txt             output of the last run

The inventory's lifted sources are reused while core/functions.tsv exists; --relift regenerates them.
"""
from __future__ import annotations

import argparse
import heapq
import json
import re
import subprocess
import sys
import time
from pathlib import Path

import live_extra
import toolchain
from build_batch import _thunk_definition, _write, build_batch
from image import GENERATED, IMAGE_PATH, ROOT, flat_image_path, load_functions
from lifter import function_name, lift_function
from meta import build_meta

LIVE_DIR = ROOT / "port" / "lifted_live"
OUT = GENERATED / "live"
CORE = OUT / "core"
EXPORTS = ("lift_ctx_create", "lift_set_image", "lift_set_env", "lift_set_thunks", "live_core_get", "live_fp_enter")
EXE_CFLAGS = ["/nologo", "/std:c17", "/TC", "/W3", "/O2", "/Z7", "/guard:cf-", "/GS-", "/D_CRT_SECURE_NO_WARNINGS"]
STACK = 64 << 20
MISSING_CODE = re.compile(r"^STOP: (?:no lifted code at ([0-9a-f]{8})|([0-9a-f]{8}) is not an instruction of the function)", re.M)


def flatten_ranges(functions) -> list[tuple[int, int, int]]:
    """Disjoint (lo, hi, function index) ascending. Where bodies overlap, the range that starts last owns the bytes."""
    spans = sorted((lo, hi, i) for i, f in enumerate(functions) for lo, hi in f.ranges)
    points = sorted({p for lo, hi, _ in spans for p in (lo, hi)})
    out: list[list[int]] = []
    active: list[tuple[int, int, int]] = []  # (-lo, function index, hi)
    k = 0
    for a, b in zip(points, points[1:]):
        while k < len(spans) and spans[k][0] <= a:
            heapq.heappush(active, (-spans[k][0], spans[k][2], spans[k][1]))
            k += 1
        while active and active[0][2] <= a:
            heapq.heappop(active)
        if not active:
            continue
        owner = active[0][1]
        if out and out[-1][2] == owner and out[-1][1] == a:
            out[-1][1] = b
        else:
            out.append([a, b, owner])
    return [tuple(r) for r in out]


def write_ranges(functions) -> int:
    """functions: every linked function, ascending by entry (the order of the runner's merged table)."""
    ranges = flatten_ranges(functions)
    lines = ["/* Generated by scripts/lift/build_live.py. */", '#include "live.h"', "", "const live_range live_ranges[] = {"]
    lines += [f"    {{0x{lo:08x}u, 0x{hi:08x}u, {fn}u}}," for lo, hi, fn in ranges] or ["    {0u, 0u, 0u},"]
    lines += ["};", f"const uint32_t live_range_count = {len(ranges)}u;"]
    _write(CORE / "live_ranges.c", "\n".join(lines) + "\n")
    return len(ranges)


def write_extra(extras) -> int:
    """Lifts the functions outside the inventory into core/live_extra.c. Returns how many have untranslated instructions."""
    declared = set(re.findall(r"LIFT_THUNK_DECL\((\w+)\)", (CORE / "batch.h").read_text()))
    thunks: dict[str, tuple[bytes, int]] = {}
    code, table, bad = [], [], 0
    for fn in extras:
        lifted = lift_function(build_meta(fn))
        thunks.update(lifted.thunks)
        code.append(lifted.code)
        table.append(f"    {{0x{fn.addr:08x}u, {function_name(fn.addr)}, {lifted.n_insn}u}},")
        bad += bool(lifted.unsupported)
    names = sorted(thunks)
    lines = ["/* Generated by scripts/lift/build_live.py. */", '#include "batch.h"', '#include "live.h"', ""]
    lines += [_thunk_definition(n, thunks[n][0]) for n in names if n not in declared] + [""] + code
    lines += ["const lift_fn_entry live_extra_fns[] = {"] + (table or ["    {0u, 0, 0u},"])
    lines += ["};", f"const uint32_t live_extra_fn_count = {len(table)}u;", "", "const lift_thunk_desc live_extra_thunks[] = {"]
    lines += [f"    {{{n}, {len(thunks[n][0])}u, 0x{thunks[n][1]:02x}u}}," for n in names] or ["    {0, 0u, 0u},"]
    lines += ["};", f"const uint32_t live_extra_thunk_count = {len(names)}u;"]
    _write(CORE / "live_extra.c", "\n".join(lines) + "\n")
    return bad


def compile_core() -> list[Path]:
    sources = sorted(CORE.glob("*.c"))
    stale = [s for s in sources if not s.with_suffix(".obj").exists()
             or s.with_suffix(".obj").stat().st_mtime < s.stat().st_mtime]
    if stale:
        toolchain.run_tool(["cl", *toolchain.GENERATED_CFLAGS, "/MP", "/c", f"/I{toolchain.RUNTIME_DIR}", f"/I{LIVE_DIR}",
                            *[s.name for s in stale]], cwd=CORE)
    return [s.with_suffix(".obj") for s in sources]


def link_dll(objs: list[Path]) -> None:
    rt = OUT / "live_rt.obj"
    toolchain.run_tool(["cl", *toolchain.RUNTIME_CFLAGS, "/c", f"/I{toolchain.RUNTIME_DIR}", f"/Fo{rt}",
                        str(LIVE_DIR / "live_rt.c")], cwd=OUT)
    rsp = OUT / "lifted.rsp"
    _write(rsp, "\n".join(f'"{o}"' for o in [rt, *objs]) + "\n")
    toolchain.run_tool(["link", "/nologo", "/DLL", "/INCREMENTAL:NO", "/GUARD:NO", f"/OUT:{OUT / 'lifted.dll'}",
                        f"/IMPLIB:{OUT / 'lifted.lib'}", *[f"/EXPORT:{name}" for name in EXPORTS], f"@{rsp}"], cwd=OUT)


def build_exe() -> None:
    toolchain.run_tool(["cl", *EXE_CFLAGS, f"/I{toolchain.RUNTIME_DIR}", f"/Fo{OUT / 'live_main.obj'}",
                        f"/Fe{OUT / 'live.exe'}", str(LIVE_DIR / "live_main.c"), "/link", "/INCREMENTAL:NO", "/DEBUG",
                        f"/STACK:{STACK}", str(OUT / "lifted.lib")], cwd=OUT)


def build_dll(args, timings) -> None:
    def timed(name, fn, *a, **kw):
        t0 = time.perf_counter()
        result = fn(*a, **kw)
        timings[name] = timings.get(name, 0.0) + time.perf_counter() - t0
        return result

    functions = list(load_functions())
    if args.slice:
        functions = functions[args.slice[0]:args.slice[0] + args.slice[1]]
    entries = [f.addr for f in functions]
    if args.relift or not (CORE / "functions.tsv").exists():
        batch = timed("lift", build_batch, entries, CORE, None, jobs=args.jobs, build=False)
        bad = sum(1 for f in batch.functions.values() if f.unsupported)
        print(f"lifted {len(batch.functions)} functions, {sum(f.n_insn for f in batch.functions.values())} "
              f"instructions, {batch.n_thunks} thunks, {bad} with untranslated instructions", flush=True)
        args.relift = False
    listed = [int(line.split("\t")[0], 16) for line in (CORE / "functions.tsv").read_text().splitlines()[1:]]
    if listed != entries:
        raise toolchain.BuildError("core/functions.tsv lists other functions than requested; use --relift")
    extras = live_extra.load_extra()
    bad = timed("extra", write_extra, extras)
    n_ranges = write_ranges(sorted(functions + extras, key=lambda f: f.addr))
    print(f"{len(extras)} extra functions ({bad} with untranslated instructions), {n_ranges} ranges", flush=True)
    timed("compile", compile_core)
    timed("link", link_dll, sorted(CORE.glob("*.obj")))
    flat_image_path()
    if not (OUT / "image.bin").exists():
        (OUT / "image.bin").write_bytes((GENERATED / "image.bin").read_bytes())


SDK_LIBS = ("kernel32", "user32", "gdi32", "advapi32", "ws2_32", "winmm", "ole32", "oleaut32", "shell32", "version",
            "comdlg32", "shlwapi", "rpcrt4", "wldap32", "opengl32")


def stack_bytes_table() -> Path:
    """name -> argument bytes of the stdcall Win32 functions, read from the SDK's 32-bit import libraries."""
    path = OUT / "stack_bytes.tsv"
    if not path.exists():
        env = {k.upper(): v for k, v in toolchain.msvc_env("x64").items()}
        lib_dir = Path(env["WINDOWSSDKDIR"]) / "Lib" / env["WINDOWSSDKLIBVERSION"].strip("\\") / "um" / "x86"
        rows: dict[str, str] = {}
        for lib in SDK_LIBS:
            listing = toolchain.run_tool(["dumpbin", "/nologo", "/linkermember:1", str(lib_dir / f"{lib}.lib")], cwd=OUT)
            for name, size in re.findall(r"__imp__(\w+)@(\d+)\s", listing):
                rows.setdefault(name, size)
        _write(path, "".join(f"{name}\t{size}\n" for name, size in sorted(rows.items())))
    return path


def run_live(extra_args) -> tuple[int, str]:
    proc = subprocess.run([str(OUT / "live.exe"), "--image", str(OUT / "image.bin"), "--game-dir", str(IMAGE_PATH.parent),
                           "--profile", str(OUT / "profile"), *extra_args], capture_output=True, text=True, errors="replace")
    text = proc.stdout + proc.stderr
    (OUT / "last_run.txt").write_text(text, encoding="utf-8", newline="\n")
    return proc.returncode, text


STATUS = LIVE_DIR / "status.json"
COUNTERS = {
    "instructions_executed": r"^instructions executed:\s+(\d+)",
    "functions_executed": r"^functions executed:\s+(\d+) of \d+",
    "functions_linked": r"^functions executed:\s+\d+ of (\d+)",
    "distinct_instructions_reached": r"^distinct instructions reached:\s+(\d+) of \d+",
    "instructions_linked": r"^distinct instructions reached:\s+\d+ of (\d+)",
    "static_imports_with_shim": r"^static imports with a shim:\s+(\d+) of \d+",
    "static_imports": r"^static imports with a shim:\s+\d+ of (\d+)",
}


def write_status(text: str) -> None:
    """Records the last real run (never a survey) in port/lifted_live/status.json."""
    stop = re.search(r"^STOP: (.*)$", text, re.M)
    reached = re.findall(r"^REACHED: (.*)$", text, re.M)
    status = {"reached": reached, "stopped_at": stop.group(1) if stop else None,
              "extra_functions": len(live_extra.load_rows())}
    for key, pattern in COUNTERS.items():
        hit = re.search(pattern, text, re.M)
        status[key] = int(hit.group(1)) if hit else None
    STATUS.write_text(json.dumps(status, indent=2) + "\n", encoding="utf-8", newline="\n")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--slice", nargs=2, type=int, metavar=("START", "COUNT"), help="only these inventory rows")
    ap.add_argument("--relift", action="store_true", help="regenerate the inventory's lifted sources")
    ap.add_argument("--exe-only", action="store_true", help="rebuild live.exe only")
    ap.add_argument("--jobs", type=int, default=None, help="lifter processes")
    ap.add_argument("--run", action="store_true", help="run after building; add missing code and repeat")
    ap.add_argument("--max-rounds", type=int, default=200, help="rebuilds a --run may do for missing code")
    ap.add_argument("--survey", action="store_true",
                    help="with --run: imports without a shim return 0 so one run lists many (not execution)")
    ap.add_argument("live_args", nargs="*", help="arguments passed to live.exe (after --)")
    args = ap.parse_args(argv)
    timings: dict[str, float] = {}
    t_start = time.perf_counter()
    try:
        if not args.exe_only:
            build_dll(args, timings)
        build_exe()
        if args.survey:
            args.live_args += ["--survey", str(stack_bytes_table())]
        code, text, found = 0, "", []
        for _ in range(args.max_rounds if args.run else 0):
            code, text = run_live(args.live_args)
            hit = MISSING_CODE.search(text)
            # A survey run goes on after calls that did nothing, so where it ends up is not evidence of real code.
            added = live_extra.add([int(hit.group(1) or hit.group(2), 16)], "run") if hit and not args.survey else []
            if not added:
                break
            found += added
            build_dll(args, timings)
    except toolchain.BuildError as error:
        print(str(error)[-6000:], file=sys.stderr)
        return 1
    print(", ".join(f"{k} {v:.1f}s" for k, v in timings.items()) + f", total {time.perf_counter() - t_start:.1f}s")
    if args.run and not args.survey:
        write_status(text)
    if args.run:
        if found:
            print(f"added {len(found)} functions outside the inventory: " + " ".join(f"{e:08x}" for e in found[:40])
                  + (" ..." if len(found) > 40 else ""))
        shown = [line for line in text.splitlines() if not line.startswith(("imports called:", "-> "))]
        print("\n".join(line[:460] for line in shown[-14:]))
        return code
    print(OUT / "live.exe")
    return 0


if __name__ == "__main__":
    sys.exit(main())
