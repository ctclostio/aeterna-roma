"""Holds the live build's inline runtime header to the runtime it copies.

    python scripts/lift/check_fast_rt.py [--root <checkout>] [--header <file>]

The live build compiles its hottest lifted functions with <root>/port/lifted_live/fast_inc/lift_rt.h first on the
include path (build_live.py, compile_core). That header replaces functions of port/lifted_runtime/lift_rt.c
(memory accessors, push/pop, flag helpers) with inline copies. The lifted tier's own tests run lift_rt.c's
definitions only, so a copy that drifts makes the hot code compute something else than the rest with no test failing.
This check compares what the two do, not their text. Without the header it says so in one line and exits 0.

What is compared is read from the header, not listed here:

  - the compiler's preprocessor says which functions declared in lift_rt.h are macros once the header is in front.
    Each must take the context and up to three integers, which is all the driver can call;
  - every other macro the header leaves defined, and every function it defines that none of those replacements
    reaches, is code the comparison would never run.

Whatever falls outside is named and fails the check, so a function added to the header is covered or reported.

The differential program has three parts. One translation unit calls each replaced function with the header in
front of the runtime's, the include order of the hot code; a second makes the same calls seeing lift_rt.h alone,
so they go to lift_rt.c; the driver (DRIVER below) runs both on two contexts prepared alike and compares all a
call leaves: how it ended (returned, or ended the trial as a fault does), the result, the registers, the seven
flags, the step count, the terminal, the pages it mapped and every byte of the mapped pages, and how often it
evaluated its operands. Inputs are the operands and ESP: every pair of them over the edge values of each operand
size and addresses around every page situation (arena, image and TEB pages, mapped or not), under four incoming
flag states; each of them at every address whose page number is one bit away from a mapped page's; then 8192
pseudo-random cases from a fixed seed. The two units are built with the flags the live build gives hot code
(LIVE_GEN_CFLAGS of <root>'s build_live.py) and again with those of the other generated code (/Od).

The header and <root>'s runtime are copied into generated/lifted/fast_rt_check/src and built from there: <root> is
only read, the inputs cannot change under the build, and a header given with --header finds the runtime it
includes by relative path. A header that includes further files of its own is not supported and fails to build.
"""
