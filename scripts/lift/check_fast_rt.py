class CheckError(RuntimeError):
    pass


def header_path(root: Path) -> Path:
    return root / HEADER


def _write(path: Path, text: str) -> None:
    path.write_text(text, encoding="ascii", newline="\n")


def logical_lines(text: str) -> list[str]:
    """C source lines with comments removed and continued lines joined."""
    text = re.sub(r"/\*.*?\*/", " ", text.replace("\r\n", "\n"), flags=re.S)
    return re.sub(r"//[^\n]*", "", text).replace("\\\n", " ").split("\n")


def leftover_macros(text: str) -> dict[str, str]:
    """name -> replacement text of every macro the header still defines at its end, its include guard left out."""
    macros: dict[str, str] = {}
    guard = None
    for line in logical_lines(text):
        if m := DEFINE.match(line):
            if m.group(1) == guard and not macros and not m.group(3).strip():
                continue
            macros[m.group(1)] = m.group(3)
        elif m := UNDEF.match(line):
            macros.pop(m.group(1), None)
        elif (m := IFNDEF.match(line)) and guard is None and not macros:
            guard = m.group(1)
    return macros


def runtime_functions(text: str) -> dict[str, tuple[str, list[str]]]:
    """name -> (result type, parameter declarations) of every function lift_rt.h declares, in its order."""
    body = " ".join(line for line in logical_lines(text) if not line.lstrip().startswith("#"))
    while (flat := re.sub(r"\{[^{}]*\}", " ", body)) != body:  # structure and enumeration bodies
        body = flat
    out = {}
    for statement in body.split(";"):
        m = PROTOTYPE.fullmatch(statement)
        if m and m.group(1).strip() and not m.group(1).lstrip().startswith("typedef"):
            out[m.group(2)] = (" ".join(m.group(1).split()), [" ".join(p.split()) for p in m.group(3).split(",")])
    return out


def operand_types(signature: tuple[str, list[str]]) -> list[str]:
    """Types of the integer operands after the context; CheckError when the driver cannot make the call."""
    result, params = signature
    if result not in (*INTEGERS, "void"):
        raise CheckError(f"its result type '{result}' is not one the driver compares")
    if not re.fullmatch(r"(const )?lift_ctx \*\s*\w+", params[0]):
        raise CheckError("it does not take the context first")
    types = [p.rsplit(" ", 1)[0] if re.fullmatch(r"[\w ]+ \w+", p) else p for p in params[1:]]  # a pointer stays whole
    if len(types) > MAX_ARGS or any(t not in INTEGERS for t in types):
        raise CheckError(f"its operands ({', '.join(params[1:])}) are not up to {MAX_ARGS} integers")
    return types


def defined_functions(text: str) -> dict[str, set[str]]:
    """name -> identifiers in its body, for every function defined at file scope of preprocessed C text."""
    tokens = TOKEN.findall(text)
    out: dict[str, set[str]] = {}
    i = 0
    while i < len(tokens):
        if tokens[i] != "{":
            i += 1
            continue
        end, depth = i, 0
        while end < len(tokens):  # the matching brace
            depth += (tokens[end] == "{") - (tokens[end] == "}")
            if depth == 0:
                break
            end += 1
        if i and tokens[i - 1] == ")":  # a body follows a parameter list; the name stands before the list
            k, depth = i - 1, 0
            while k >= 0:
                depth += (tokens[k] == ")") - (tokens[k] == "(")
                if depth == 0:
                    break
                k -= 1
            if k > 0 and NAME.fullmatch(tokens[k - 1]):
                out[tokens[k - 1]] = {t for t in tokens[i + 1:end] if NAME.fullmatch(t)}
        i = end + 1
    return out


def stage(root: Path, header: Path) -> tuple[Path, Path]:
    """Copies the header and root's runtime into the work folder, laid out as in a checkout. Returns the two
    include folders: the header's and the runtime's."""
    fast_dir, rt_dir = WORK / "src" / HEADER.parent, WORK / "src" / RUNTIME
    for folder in (fast_dir, rt_dir):
        folder.mkdir(parents=True, exist_ok=True)
        for old in folder.iterdir():
            old.unlink()
    (fast_dir / HEADER.name).write_bytes(header.read_bytes())
    for source in sorted((root / RUNTIME).iterdir()):
        if source.suffix == ".h" or source.name == "lift_rt.c":
            (rt_dir / source.name).write_bytes(source.read_bytes())
    if not (rt_dir / "lift_rt.c").exists() or not (rt_dir / "lift_rt.h").exists():
        raise CheckError(f"{root / RUNTIME} has no lift_rt.c and lift_rt.h")
    return fast_dir, rt_dir


def compiler_view(fast_dir: Path, rt_dir: Path, declared: dict) -> tuple[list[str], dict[str, set[str]]]:
    """What a translation unit with the header in front holds, from the compiler's own preprocessor: the declared
    runtime functions that are macros there, and the functions the header's own lines define."""
    probe = ['#include "lift_rt.h"'] + [f'#ifdef {name}\nfrt_macro "{name}"\n#endif' for name in declared]
    _write(WORK / "frt_probe.c", "\n".join(probe) + "\n")
    out = WORK / "frt_probe.i"
    toolchain.run_tool(["cl", "/nologo", "/std:c17", "/TC", "/P", f"/Fi{out}", f"/I{fast_dir}", f"/I{rt_dir}", "frt_probe.c"], cwd=WORK)
    want = os.path.normcase(os.path.normpath(fast_dir / HEADER.name))
    own, inside = [], False
    text = out.read_text(encoding="utf-8", errors="replace")
    for line in text.splitlines():
        if m := LINE.match(line):
            inside = os.path.normcase(os.path.normpath(m.group(1).replace("\\\\", "\\"))) == want
        elif inside:
            own.append(line)
    if not own:
        raise CheckError("the preprocessed translation unit shows no line of the header: it was not the lift_rt.h found first")
    return re.findall(r'^frt_macro "(\w+)"', text, re.M), defined_functions("\n".join(own))


def side_source(side: str, ops: dict[str, tuple[str, list[str]]]) -> str:
    """The calls under test as one side's translation unit: the same text for both but for the table's name and
    the proof that the side sees what it should."""
    fast = side == "fast"
    wrong = "not a macro here, so the fast header is not in use" if fast else "a macro here, so this is not lift_rt.c alone"
    lines = [f"/* Generated by scripts/lift/check_fast_rt.py: the calls under test, {'with the fast header' if fast else 'against lift_rt.c'}. */",
             '#include "frt.h"', ""]
    for name in ops:
        lines += [f"#if{'n' if fast else ''}def {name}", f'#error "{name}: {wrong}"', "#endif"]
    lines.append("")
    for name, (result, types) in ops.items():
        call = f"{name}(c{''.join(f', ({t})FRT_X({i})' for i, t in enumerate(types))})"
        body = f"{call}; return 0u;" if result == "void" else f"return (uint32_t){call};"
        unused = "" if types else "(void)x; (void)evals; "
        lines.append(f"static uint32_t op_{name}(lift_ctx *c, const uint32_t *x, uint32_t *evals) {{ {unused}{body} }}")
    lines += ["", f"const frt_op frt_{side}_ops[] = {{"]
    lines += [f'    {{"{name}", {len(types)}u, {int(result != "void")}u, op_{name}}},' for name, (result, types) in ops.items()]
    lines += ["};", f"const uint32_t frt_{side}_count = {len(ops)}u;"]
    return "\n".join(lines) + "\n"


def hot_cflags(root: Path) -> tuple[list[str], str]:
    """The flags root's live build compiles hot generated code with, and where they were found."""
    path = root / "scripts" / "lift" / "build_live.py"
    found = re.search(r"^LIVE_GEN_CFLAGS = (\[.*\])$", path.read_text(encoding="utf-8"), re.M) if path.exists() else None
    if found:
        return ast.literal_eval(found.group(1)), f"LIVE_GEN_CFLAGS of {path}"
    return ["/O2" if f == "/Od" else f for f in toolchain.GENERATED_CFLAGS], f"{path} names no LIVE_GEN_CFLAGS: /O2 taken for hot code"


def build(fast_dir: Path, rt_dir: Path, ops, variants: dict[str, list[str]]) -> dict[str, Path]:
    """One differential program per set of flags: lift_rt.c and the driver built as hand-written runtime code,
    the two sides with the flags under test."""
    _write(WORK / "frt.h", FRT_H.replace("@MAX_ARGS@", str(MAX_ARGS)))
    _write(WORK / "frt_main.c", DRIVER)
    for side in ("fast", "ref"):
        _write(WORK / f"frt_{side}.c", side_source(side, ops))
    common = []
    for name, source in (("lift_rt", rt_dir / "lift_rt.c"), ("frt_main", WORK / "frt_main.c")):
        common.append(WORK / f"{name}.obj")
        toolchain.run_tool(["cl", *toolchain.RUNTIME_CFLAGS, "/c", f"/I{rt_dir}", f"/I{WORK}", f"/Fo{common[-1]}", str(source)], cwd=WORK)
    exes = {}
    for label, cflags in variants.items():
        tag = re.sub(r"\W+", "_", label).strip("_")
        sides = []
        for side, include in (("fast", [f"/I{fast_dir}", f"/I{rt_dir}"]), ("ref", [f"/I{rt_dir}"])):
            sides.append(WORK / f"frt_{side}_{tag}.obj")
            toolchain.run_tool(["cl", *cflags, "/c", *include, f"/I{WORK}", f"/Fo{sides[-1]}", f"frt_{side}.c"], cwd=WORK)
        exes[label] = WORK / f"frt_{tag}.exe"
        toolchain.link_exe(exes[label], [*common, *sides])
    return exes


def run(exe: Path, ops) -> dict[str, tuple]:
    """name -> ("same", cases, faults) or ("different", case, detail lines), one entry for every function."""
    proc = subprocess.run([str(exe)], capture_output=True, text=True, errors="replace")
    out: dict[str, tuple] = {}
    lines = proc.stdout.splitlines()
    for i, line in enumerate(lines):
        word = line.split()
        if line.startswith("same ") and len(word) == 4:
            out[word[1]] = ("same", int(word[2]), int(word[3]))
        elif line.startswith("different ") and len(word) == 3:
            detail = []
            for d in lines[i + 1:]:
                if not d.startswith(" "):
                    break
                detail.append(d)
            out[word[1]] = ("different", int(word[2]), detail)
    ended = bool(lines) and lines[-1].startswith("end ")
    if not ended or proc.returncode not in (0, 1) or list(out) != list(ops) or any(v[0] == "same" and not v[1] for v in out.values()):
        raise CheckError(f"{exe.name} did not run every function (exit code {proc.returncode & 0xffffffff:#x}):\n"
                         + "\n".join(lines[-12:]) + proc.stderr[-2000:])
    return out


def surface(fast_dir: Path, rt_dir: Path) -> tuple[dict[str, tuple[str, list[str]]], list[str]]:
    """What the header puts in front of generated code: the replaced runtime functions the driver can call
    (name -> result type, operand types), and a line for each thing it leaves behind that the driver cannot run."""
    macros = leftover_macros((fast_dir / HEADER.name).read_text(encoding="utf-8", errors="replace"))
    declared = runtime_functions((rt_dir / "lift_rt.h").read_text(encoding="utf-8", errors="replace"))
    replaced, inline = compiler_view(fast_dir, rt_dir, declared)
    uncovered = [f"macro {name}: no function declared in lift_rt.h, so nothing to compare it with" for name in macros if name not in declared]
    uncovered += [f"{name}: a macro once the header is included, but not one its text leaves defined" for name in replaced if name not in macros]
    uncovered += [f"macro {name}: left defined by the header's text, but not a macro once the header is included"
                  for name in macros if name in declared and name not in replaced]
    ops = {}
    for name in replaced:
        try:
            ops[name] = (declared[name][0], operand_types(declared[name]))
        except CheckError as error:
            uncovered.append(f"{name}: {error}")
    reached, pending = set(), [n for name in replaced for n in NAME.findall(macros.get(name, "")) if n in inline]
    while pending:
        name = pending.pop()
        if name not in reached:
            reached.add(name)
            pending += [n for n in inline[name] if n in inline]
    uncovered += [f"function {name}: defined by the header, reached from no replaced runtime function" for name in inline if name not in reached]
    print(f"the header defines {len(inline)} functions and replaces {len(replaced)} runtime functions", flush=True)
    return ops, uncovered


def check(root: Path, header: Path) -> int:
    WORK.mkdir(parents=True, exist_ok=True)
    fast_dir, rt_dir = stage(root, header)
    sha = {p.name: hashlib.sha256(p.read_bytes()).hexdigest()[:16] for p in (fast_dir / HEADER.name, rt_dir / "lift_rt.c")}
    print(f"header     {header}  sha256 {sha[HEADER.name]}\nruntime    {root / RUNTIME / 'lift_rt.c'}  sha256 {sha['lift_rt.c']}", flush=True)
    ops, uncovered = surface(fast_dir, rt_dir)
    if not ops and not uncovered:
        print("fast-rt: the header replaces no runtime function, so there is nothing to compare")
        return 0

    hot, where = hot_cflags(root)
    variants = {f"hot code flags ({' '.join(f for f in hot if f.startswith('/O'))})": hot}
    if hot != toolchain.GENERATED_CFLAGS:
        variants[f"other generated code flags ({' '.join(f for f in toolchain.GENERATED_CFLAGS if f.startswith('/O'))})"] = toolchain.GENERATED_CFLAGS
    print(f"builds     {'; '.join(variants)}  [{where}]", flush=True)
    results = {label: run(exe, ops) for label, exe in build(fast_dir, rt_dir, ops, variants).items()} if ops else {}

    different = []
    for name in ops:
        outcomes = [results[label][name] for label in variants]
        if all(o[0] == "same" for o in outcomes):
            cases = " and ".join(sorted({f"{o[1]} cases ({o[2]} ending the trial)" for o in outcomes}))
            print(f"  {name}: checked {cases}{' in each build' if len(variants) > 1 else ''}")
            continue
        different.append(name)
        for label, outcome in zip(variants, outcomes):
            if outcome[0] == "same":
                print(f"  {name}: checked {outcome[1]} cases with {label}")
            else:
                print(f"  {name}: DIFFERENT with {label} at case {outcome[1]}\n" + "\n".join("    " + d for d in outcome[2]))
    for line in uncovered:
        print(f"  NOT COVERED  {line}")
    if different or uncovered:
        parts = [f"{len(different)} of {len(ops)} replaced functions differ from lift_rt.c ({', '.join(different)})"] if different else []
        parts += [f"{len(uncovered)} left by the header outside the comparison (NOT COVERED above)"] if uncovered else []
        print("fast-rt: FAILED: " + "; ".join(parts))
        return 1
    total = sum(o[1] for o in next(iter(results.values())).values())
    print(f"fast-rt: {len(ops)} replaced runtime functions behave as lift_rt.c's over {total} cases"
          + (f" in each of {len(variants)} builds" if len(variants) > 1 else "")
          + ("" if where.startswith("LIVE_GEN_CFLAGS of ") else f" [{where}]"))  # the gate shows this line only
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", type=Path, default=ROOT, help="checkout whose header, runtime and hot-code flags are used (default: this one)")
    ap.add_argument("--header", type=Path, help="this copy of the header instead of <root>'s own, against <root>'s runtime")
    args = ap.parse_args(argv)
    root = args.root.resolve()
    header = args.header.resolve() if args.header else header_path(root)
    if not header.exists():
        if args.header:
            print(f"fast-rt: FAILED: {header} does not exist", file=sys.stderr)
            return 1
        print(f"fast-rt: skipped: {root} has no {HEADER.as_posix()}, so the live build inlines no copy of the runtime there")
        return 0
    try:
        return check(root, header)
    except (toolchain.BuildError, CheckError) as error:
        print(str(error)[-6000:], file=sys.stderr)
        print("fast-rt: FAILED: the comparison did not run")
        return 1


if __name__ == "__main__":
    sys.exit(main())
