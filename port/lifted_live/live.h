/*
 * live.h - interface between the lifted core (lifted.dll: every lifted
 * function plus the lifted runtime) and the live runner (live.exe).
 *
 * In the live runner a lifted function is not a trial. Control that leaves a
 * function goes back to the runner's dispatch loop, which continues in the
 * lifted function that owns the target address or calls the host
 * implementation of an import. Guest memory is one flat host reservation.
 */
#ifndef ROME2_LIVE_H
#define ROME2_LIVE_H

#include "../lifted_runtime/lift_rt.h"

/* Values lift_ctx.jb is resumed with. */
#define LIVE_JMP_STOP 1     /* fault, exception, untranslated instruction, budget */
#define LIVE_JMP_TRANSFER 2 /* control left the current function; continue at c->eip */

/* Address ranges of lifted code, disjoint and ascending, each owned by one function. */
typedef struct live_range {
    uint32_t lo, hi; /* hi exclusive */
    uint32_t fn;     /* index into live_core.fns */
} live_range;

typedef struct live_core {
    const lift_fn_entry *fns; /* ascending by entry */
    uint32_t n_fns;
    const lift_thunk_desc *thunks;
    uint32_t n_thunks;
    const live_range *ranges;
    uint32_t n_ranges;
} live_core;

/* Generated by scripts/lift/build_live.py. live_extra_* are the functions of
 * port/lifted_live/extra_functions.tsv (code outside the inventory); range
 * owners index the inventory's and the extra functions merged by entry. */
extern const live_range live_ranges[];
extern const uint32_t live_range_count;
extern const lift_fn_entry live_extra_fns[];
extern const uint32_t live_extra_fn_count;
extern const lift_thunk_desc live_extra_thunks[];
extern const uint32_t live_extra_thunk_count;

const live_core *live_core_get(void);
/* Makes the host x87 state and MXCSR the guest's: a 32-bit Windows thread's
 * initial state (FCW 0x027f, MXCSR 0x1f80, empty register stack). */
void live_fp_enter(lift_ctx *c);

#endif /* ROME2_LIVE_H */
